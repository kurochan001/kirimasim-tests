// IEEE 1800-2023 §3.14.2.2: timeunit and timeprecision give the interface a
// time unit of 10ns and a precision of 1ns. §3.14.2.3: a delay in an always
// block of the interface uses that unit, so its #5 is 50ns and the clock has
// a period of 100ns, whatever the time unit of the module that observes it.
// The observing module has a unit of 1ns, and §20.3.3: its $realtime reports
// the two posedges of the interface clock at 50.0 and 150.0.

`timescale 1ns / 1ps

interface clk_if;
  timeunit 10ns;
  timeprecision 1ns;
  logic clk = 0;
  always #5 clk = ~clk;   // changes every 50ns
endinterface

module test_timeunit_interface_clock;
  timeunit 1ns;
  timeprecision 1ps;

  clk_if c();

  initial begin
    @(posedge c.clk);
    $display("%0.1f ns: first posedge", $realtime);
    @(posedge c.clk);
    $display("%0.1f ns: second posedge", $realtime);
    $finish;
  end
endmodule
