module pl_kinds (pl_ifc bus,
                 input pl_struct_t s,
                 input pl_union_t u,
                 input logic [7:0] arr [3],
                 input var event ev,
                 input wire [3:0] n,
                 input var int v,
                 output logic [7:0] o);
  int hits = 0;
  always @(ev) hits++;
  assign o = bus.d ^ {s.a, s.b} ^ u.all ^ arr[1] ^ {4'b0, n} ^ v[7:0];
  task report;
    $display("kinds o=%h hits=%0d arr=%h %h %h", o, hits, arr[0], arr[1], arr[2]);
  endtask
endmodule

