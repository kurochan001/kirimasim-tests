// IEEE 1800-2023 §19.8: Table 19-5 provides set_inst_name(string) for a
// covergroup, and it sets the name of the instance it is called on to the
// given string. That name is the name option of Table 19-1 (19.7), which the
// instance holds in option.name. §19.7: an option assignment in the
// definition is evaluated when the instance is made, and its value affects
// only that instance, so g1 and g2 of cg start with the names that their
// arguments give.
//
// The test prints the names of g1 and g2, then renames g1 and then g2 and
// prints both names after each call. A call that renamed every instance of
// the covergroup would change g2 on the second line, and a call that left
// option.name alone would keep "first" there. cu has no name option, so the
// names of u1 and u2 are generated by the tool and are not printed: after
// u1 is renamed, the test prints the new name of u1 and whether u2 still has
// the name it had before the call.
//
// Icarus Verilog 13.0 does not implement covergroups. The 5.054 release
// of Verilator reads an empty option.name for every instance, also for g1
// and g2, whose definition sets it, before and after set_inst_name, so the
// cited clauses alone decide this test.

module test_cg_set_inst_name_option_name;
  bit [1:0] a;

  covergroup cg (string n);
    option.name = n;
    cp: coverpoint a;
  endgroup

  covergroup cu;
    cp: coverpoint a;
  endgroup

  cg g1 = new("first");
  cg g2 = new("second");
  cu u1 = new;
  cu u2 = new;
  string u2_name;

  initial begin
    $display("g1 \"%s\" g2 \"%s\"", g1.option.name, g2.option.name);
    g1.set_inst_name("n1");
    $display("g1 \"%s\" g2 \"%s\"", g1.option.name, g2.option.name);
    g2.set_inst_name("n2");
    $display("g1 \"%s\" g2 \"%s\"", g1.option.name, g2.option.name);
    u2_name = u2.option.name;
    u1.set_inst_name("m1");
    $display("u1 \"%s\" u2 unchanged %0d", u1.option.name, u2.option.name == u2_name);
  end
endmodule
