"""Check the libfst reader harness on a small committed FST fixture.

The fixture is generated by tools/fst_fixture.c against the same pinned libfst
source as the reader. The Check workflow does not require libfst, so this test
is skipped when no source tree is available.
"""

import unittest
from pathlib import Path

import fst_reader

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tools" / "fixtures" / "fst" / "simple.fst"
EXPECTED = ROOT / "tools" / "fixtures" / "fst" / "simple.expected"


class FstReaderTests(unittest.TestCase):
    def setUp(self):
        self.source = fst_reader.find_source()
        if self.source is None:
            self.skipTest("libfst source not found; set LIBFST_SRC")

    def test_reads_hierarchy_and_values(self):
        text = fst_reader.read(FIXTURE, [0, 10], libfst_src=self.source)
        self.assertEqual(text, EXPECTED.read_text(encoding="utf-8"))

    def test_fixture_is_fst_not_vcd(self):
        data = FIXTURE.read_bytes()
        self.assertGreaterEqual(len(data), 9)
        self.assertEqual(data[0], 0)
        self.assertEqual(int.from_bytes(data[1:9], "big"), 329)
        self.assertNotEqual(data[:5], b"$date")

    def test_missing_source_is_reported(self):
        with self.assertRaises(FileNotFoundError):
            fst_reader.build(ROOT / "tools" / "fixtures" / "fst" / "not-libfst")


if __name__ == "__main__":
    unittest.main()
