#!/usr/bin/env python3
"""Generate the complete bilingual generator catalog from current suite metadata."""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import sys

import doc_localization as locale
import suite_results

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'generators'))
import interaction_models


def build():
    counts=defaultdict(int);chapters=defaultdict(set)
    for test in suite_results.find_tests():
        fields=suite_results.header(test)
        name=fields.get('generator','').split('@')[0]
        if not name:continue
        counts[name]+=1
        chapters[name].add(int(test.parent.name.removeprefix('ch')))
    models={}
    for plan in interaction_models.registered():
        witness=ROOT/plan.path(plan.model.select()[0])
        name=suite_results.header(witness)['generator'].split('@')[0]
        if name in models:raise ValueError('multiple finite models need a combined description: '+name)
        models[name]=plan.witness
    descriptions=json.loads((ROOT/'tools/doc_locales/generator_scopes.json').read_text(encoding='utf-8'))['scopes']
    missing=set(counts)-set(models)-set(descriptions)
    if missing:raise ValueError('missing bilingual generator scope: '+', '.join(sorted(missing)))
    outputs={}
    for language,filename in [('en','docs/generators.md'),('ja','docs/generators.ja.md')]:
        japanese=language=='ja'
        target=ROOT/filename
        lines=['# 生成器カタログ' if japanese else '# Generator catalog','',
               '[English](generators.md) / [日本語](generators.ja.md)','',
               (f'現在の{len(counts)}生成器から{sum(counts.values()):,}件のテストを生成しています。'
                if japanese else f'The current {len(counts)} generators produce {sum(counts.values()):,} tests.'),
               ('通常の全件数と、有限クロスモデルの短時間選択の件数は別です。各行は通常の生成件数です。'
                if japanese else 'Full generated-test counts and finite-model short selections are distinct. Rows below count full generated tests.'), '',
               ('この資料は`tools/generator_catalog.py`で生成します。生成器の因子・合法条件・観測点と期待値は、各ソースと[クロス設計](interaction-verification.md)を確認してください。'
                if japanese else 'Generated by `tools/generator_catalog.py`. Consult each source and the [interaction guide](interaction-verification.en.md) for factors, legality, observations and expected values.'), '',
               '| 生成器 | 章 | テスト数 | 確認する動作 |' if japanese else '| Generator | Chapters | Tests | Observation scope |',
               '| --- | --- | ---: | --- |']
        for name in sorted(counts):
            if name in models:
                scope=models[name] if japanese else locale.inline(models[name],language,
                    ROOT/'docs/generators.ja.md',target)
            else:
                scope=descriptions[name][language]
            scope=scope.replace('|','\\|').replace('\n',' ')
            chapter=', '.join(map(str,sorted(chapters[name])))
            lines.append(f'| [`{name}`](../generators/{name}.py) | {chapter} | {counts[name]} | {scope} |')
        lines += ['', '```sh','python3 tools/generator_catalog.py --update',
                  'python3 tools/generator_catalog.py --check','```','']
        outputs[target]='\n'.join(lines)
    paired=locale.parallel_anchors({language:outputs[ROOT/name] for language,name in
        [('en','docs/generators.md'),('ja','docs/generators.ja.md')]})
    return {ROOT/name:paired[language] for language,name in
        [('en','docs/generators.md'),('ja','docs/generators.ja.md')]}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--update',action='store_true');mode.add_argument('--check',action='store_true')
    args=parser.parse_args()
    outputs=build();stale=[]
    for path,text in outputs.items():
        if args.update:path.write_text(text,encoding='utf-8')
        elif not path.is_file() or path.read_text(encoding='utf-8')!=text:stale.append(str(path.relative_to(ROOT)))
    if stale:
        print('stale generator catalog: '+', '.join(stale),file=sys.stderr)
        return 1
    print(f'{len(outputs)} generator catalog language versions are current.')
    return 0


if __name__=='__main__':raise SystemExit(main())
