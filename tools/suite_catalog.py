#!/usr/bin/env python3
"""Writes the catalog of the tests, docs/tests/, from their metadata, or checks
that it is up to date.

Usage:
    python3 tools/suite_catalog.py            print the files it would write
    python3 tools/suite_catalog.py --update   rewrite docs/tests/
    python3 tools/suite_catalog.py --check    exit with 1 if docs/tests/ is out of date

docs/tests/README.md lists the chapters, and docs/tests/chNN.md lists every
test of chapter NN with what it checks (its :description:), the clauses it
cites (:lrm:), the release its expected output was recorded with (:oracle:)
and notes on its kind. Hand-written tests come first, in the order of the
first clause they cite; generated tests follow, grouped by generator.
"""

import argparse
import re
import sys
from pathlib import Path

import suite_results
import suite_stats

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs" / "tests"
ORACLES = {"icarus": "Icarus Verilog 13.0", "verilator": "Verilator 5.052",
           "spec": "standard only"}


def clause_key(clause: str) -> tuple:
    """Sorts 4.4.2 before 4.10 and the annexes (H.7.4) after the clauses."""
    parts = clause.split(".")
    return tuple((0, int(p), "") if p.isdigit() else (1, 0, p) for p in parts)


def cell(text: str) -> str:
    """text in a table cell, where | ends the cell, a backquote would start a code
    span (descriptions write compiler directives such as `define) and < could
    start an HTML tag."""
    return text.replace("|", "\\|").replace("`", "\\`").replace("<", "&lt;").strip()


def description(fields: dict[str, str]) -> str:
    text = fields.get("description", "")
    return re.sub(r"\s*\(IEEE 1800-2023[^)]*\)\s*$", "", text)


def notes(fields: dict[str, str]) -> str:
    out = []
    if "should_fail_because" in fields:
        out.append("illegal design")
    if "expected_exit" in fields:
        out.append("exit code")
    if "dpi_c" in fields:
        out.append("DPI")
    if "vpi_c" in fields:
        out.append("VPI")
    if "files" in fields:
        out.append("several files")
    if "args" in fields:
        out.append("plusargs")
    if fields.get("fourstate") == "yes":
        out.append("x/z")
    return ", ".join(out)


def entry(test: Path) -> dict:
    fields = suite_results.header(test)
    clauses = fields.get("lrm", "").split()[1:]
    return {"name": test.stem, "path": test.relative_to(ROOT).as_posix(),
            "chapter": int(test.parent.name.removeprefix("ch")),
            "generator": fields.get("generator", "").split("@")[0],
            "clauses": clauses, "key": clause_key(clauses[0]) if clauses else (),
            "what": description(fields), "oracle": ORACLES[suite_stats.oracle_kind(fields)],
            "notes": notes(fields)}


def table(entries: list[dict]) -> list[str]:
    lines = ["| Test | What it checks | Clauses | Expected output recorded with | Notes |",
             "| --- | --- | --- | --- | --- |"]
    for e in entries:
        lines.append(f"| [`{e['name']}`](../../{e['path']}) | {cell(e['what'])} | "
                     f"{' '.join(e['clauses'])} | {e['oracle']} | {e['notes']} |")
    return lines


def chapter_page(chapter: int, entries: list[dict]) -> str:
    title = suite_stats.CHAPTERS[chapter]
    written = sorted((e for e in entries if not e["generator"]),
                     key=lambda e: (e["key"], e["name"]))
    generated = [e for e in entries if e["generator"]]
    lines = [f"# Clause {chapter}: {title}", "",
             f"[All chapters](README.md). {len(entries)} tests"
             + (f", {len(generated)} of them generated" if generated else "") + ". "
             "This page is written by `tools/suite_catalog.py` from the metadata of the "
             "tests; edit the tests, not this page.", ""]
    if written:
        lines += table(written) + [""]
    for g in sorted({e["generator"] for e in generated}):
        group = sorted((e for e in generated if e["generator"] == g),
                       key=lambda e: e["name"])
        lines += [f"## Generated by `generators/{g}.py`", "",
                  f"{len(group)} tests; see \"Generated tests\" in the suite's README.", ""]
        lines += table(group) + [""]
    return "\n".join(lines)


def index_page(by_chapter: dict[int, list[dict]]) -> str:
    lines = ["# Catalog of the tests", "",
             "One page for each clause of IEEE 1800-2023 that has tests, listing every test "
             "with what it checks (`:description:`), the clauses it cites (`:lrm:`), the "
             "release its expected output was recorded with (`:oracle:`; \"standard only\" "
             "when neither Icarus Verilog 13.0 nor Verilator 5.052 produces it) and notes: "
             "illegal designs, tests of the exit code, tests with C code (DPI, VPI), with "
             "several source files or with plusargs, and tests whose result depends on x or "
             "z values. The comment at the top of each test explains in more detail what the "
             "cited clauses require and how the test observes it.", "",
             "These pages are written by `tools/suite_catalog.py` from the metadata of the "
             "tests (`python3 tools/suite_catalog.py --update`), and the check workflow "
             "fails when they are out of date.", "",
             "| Clause | Title | Tests | Generated |", "| ---: | --- | ---: | ---: |"]
    for chapter, title in suite_stats.CHAPTERS.items():
        entries = by_chapter.get(chapter)
        if not entries:
            lines.append(f"| {chapter} | {title} | — | |")
            continue
        generated = sum(1 for e in entries if e["generator"])
        lines.append(f"| {chapter} | [{title}](ch{chapter}.md) | {len(entries)} | "
                     f"{generated or ''} |")
    return "\n".join(lines) + "\n"


def pages() -> dict[Path, str]:
    by_chapter: dict[int, list[dict]] = {}
    for test in suite_results.find_tests():
        e = entry(test)
        by_chapter.setdefault(e["chapter"], []).append(e)
    files = {CATALOG / "README.md": index_page(by_chapter)}
    for chapter, entries in by_chapter.items():
        files[CATALOG / f"ch{chapter}.md"] = chapter_page(chapter, entries)
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--update", action="store_true", help="rewrite docs/tests/")
    group.add_argument("--check", action="store_true",
                       help="exit with 1 if docs/tests/ is out of date")
    args = ap.parse_args()

    files = pages()
    if not (args.update or args.check):
        for path, text in sorted(files.items()):
            sys.stdout.write(f"==> {path.relative_to(ROOT)} <==\n{text}\n")
        return 0
    present = set(CATALOG.glob("*.md")) if CATALOG.exists() else set()
    stale = sorted(present - set(files))
    changed = sorted(p for p, text in files.items()
                     if not p.exists() or p.read_text(encoding="utf-8") != text)
    if args.check:
        for p in changed + stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        if changed or stale:
            print("docs/tests/ is out of date: run python3 tools/suite_catalog.py --update")
        return 1 if changed or stale else 0
    for p in stale:
        p.unlink()
    CATALOG.mkdir(parents=True, exist_ok=True)
    for p in changed:
        p.write_text(files[p], encoding="utf-8")
    print(f"{len(files)} catalog pages; {len(changed)} written, {len(stale)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
